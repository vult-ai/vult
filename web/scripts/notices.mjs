// Writes the browser interface section of THIRD_PARTY_NOTICES.md from the npm
// lockfile, installed package licenses and the vendored notices in licenses/.
// `--check` fails when the section is out of date instead of writing it.
import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const web = fileURLToPath(new URL("..", import.meta.url));
const target = path.join(web, "..", "THIRD_PARTY_NOTICES.md");
const marker = "<!-- Browser interface notices: generated by web/scripts/notices.mjs -->";
// Bundled into the interface although npm lists them as build tools.
const bundledBuildTools = ["tailwindcss"];
// Vendored or adapted sources with their own notice files.
const vendored = [
  ["shadcn/ui primitives", "LICENSE.shadcn-ui"],
  ["Untitled UI React components", "LICENSE.untitledui-react"],
  ["TUFFUI components (https://tuffui.com)", "LICENSE.tuffui"],
  ["react-remove-scroll-bar", "LICENSE.react-remove-scroll-bar"],
  ["saxes", "LICENSE.saxes"],
  ["Geist fonts", "Geist-OFL.txt"],
];

const lock = JSON.parse(await readFile(path.join(web, "package-lock.json"), "utf8"));
const runtime = Object.entries(lock.packages)
  .filter(([key, value]) => key.startsWith("node_modules/") && (!value.dev && !value.optional || bundledBuildTools.includes(key.slice(13))))
  .map(([key, value]) => ({ name: key.replace(/^.*node_modules\//, ""), dir: key, version: value.version, license: value.license || "See text" }))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

async function licenseText(dir, declared) {
  let names = [];
  try {
    names = await readdir(path.join(web, dir));
  } catch {
    throw Error(`Install dependencies first: ${dir} is missing.`);
  }
  const file = names.find((n) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(n)) || names.find((n) => /^licen[cs]e/i.test(n));
  if (!file) return `Declared license: ${declared}. The package ships no license file.`;
  return (await readFile(path.join(web, dir, file), "utf8")).trim();
}

let section = `${marker}\n\n## Browser interface\n\nThe bundled browser interface includes these packages and adapted sources.\n\n| Package | Version | License |\n| --- | --- | --- |\n`;
for (const p of runtime) section += `| ${p.name} | ${p.version} | ${p.license} |\n`;
for (const [name, file] of vendored) {
  const text = (await readFile(path.join(web, "licenses", file), "utf8")).trim();
  section += `\n### ${name}\n\n\`\`\`text\n${text}\n\`\`\`\n`;
}
const seen = new Map();
for (const p of runtime) {
  const text = await licenseText(p.dir, p.license);
  const list = seen.get(text) || [];
  list.push(`${p.name} ${p.version}`);
  seen.set(text, list);
}
for (const [text, packages] of seen) section += `\n### ${packages.join(", ")}\n\n\`\`\`text\n${text}\n\`\`\`\n`;

const current = await readFile(target, "utf8");
const at = current.indexOf(marker);
const next = (at === -1 ? current.trimEnd() + "\n\n" : current.slice(0, at)) + section;
if (process.argv.includes("--check")) {
  if (next !== current) throw Error("THIRD_PARTY_NOTICES.md is out of date. Run node web/scripts/notices.mjs.");
  console.log("Verified the browser interface notices.");
} else {
  await writeFile(target, next);
  console.log(`Wrote notices for ${runtime.length} packages and ${vendored.length} adapted sources.`);
}
